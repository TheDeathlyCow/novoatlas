package com.thedeathlycow.novoatlas.impl.fabric.datagen;

import net.fabricmc.fabric.api.datagen.v1.FabricPackOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricDynamicRegistryProvider;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.Registries;

import java.util.concurrent.CompletableFuture;

public class BootstrappedRegistryProvider extends FabricDynamicRegistryProvider {
    public BootstrappedRegistryProvider(FabricPackOutput output, CompletableFuture<HolderLookup.Provider> registriesFuture) {
        super(output, registriesFuture);
    }

    @Override
    protected void configure(HolderLookup.Provider registries, Entries entries) {
        entries.addAll(registries.lookupOrThrow(Registries.DENSITY_FUNCTION));
    }

    @Override
    public String getName() {
        return "NovoAtlasBootstrappedRegistryProvider";
    }
}